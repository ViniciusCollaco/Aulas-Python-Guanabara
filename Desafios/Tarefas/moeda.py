def aumentar(valor):
    porcentAum = valor * 0.1
    resulAum = porcentAum + valor
    return resulAum
    
def diminuir(valor):
    porcentDim = valor * 0.13
    resulDim = valor - porcentDim
    return resulDim
    
def dobro(valor):
    resulDobr = valor * 2
    return resulDobr
    
def metade(valor):
    resultMeta = valor / 2
    return resultMeta