def aumentar(valor, taxa):
    resulAum = valor + (valor * taxa/100)
    return resulAum
    
def diminuir(valor, taxa):
    resulDim = valor - (valor * taxa/100)
    return resulDim
    
def dobro(valor):
    resulDobr = valor * 2
    return resulDobr
    
def metade(valor):
    resultMeta = valor / 2
    return resultMeta